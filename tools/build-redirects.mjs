/**
 * Writes `public/_redirects` from the subtype aliases, so a search for "true
 * summer color palette" lands on the cool summer page instead of a 404. Run it
 * after changing `SUBTYPES`; `tests/redirects.test.ts` fails if the file drifts.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../src/lib/subtypes.ts', import.meta.url), 'utf8');

export function aliasRedirects(ts = source) {
  const entries = [...ts.matchAll(/slug: '([^']+)',\s*\n\s*name: '[^']+',\s*\n\s*aliases: \[([^\]]*)\]/g)];
  const lines = [];
  for (const [, slug, rawAliases] of entries) {
    for (const alias of [...rawAliases.matchAll(/'([^']+)'/g)].map((m) => m[1])) {
      lines.push(`/${alias.replace(/\s+/g, '-')}-color-palette/ /${slug}/ 301`);
    }
  }
  return lines;
}

const body = [
  '# Generated by tools/build-redirects.mjs — do not edit by hand.',
  '# Alternative names for the twelve subtypes point at the canonical page.',
  ...aliasRedirects(),
  '',
].join('\n');

writeFileSync(new URL('../public/_redirects', import.meta.url), body);
